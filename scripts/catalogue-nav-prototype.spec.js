const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({headless:true});
  const widths = [360,390,768,1280];
  for (const width of widths) {
    const page = await browser.newPage({viewport:{width,height:900}});
    const errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
    await page.goto('http://127.0.0.1:4173/catalogue-review/car-audio-navigation-prototype.html',{waitUntil:'domcontentloaded'});
    await page.waitForFunction(()=>document.querySelector('#content [data-brand]')!==null,{timeout:15000});
    const brandCount=await page.locator('#content [data-brand]').count();
    if(brandCount!==10)throw new Error('Expected 9 Planetworld brands plus staged Hertz; got '+brandCount+' at '+width+'px');
    const labels=await page.locator('#content [data-brand]').allTextContents();
    if(labels.some(x=>/Harnesses & Trims/.test(x)))throw new Error('Harnesses & Trims incorrectly shown as a manufacturer brand');
    if(labels.some(x=>/JBL|Denon DJ/.test(x)))throw new Error('JBL or Denon DJ incorrectly shown as a Car Audio brand');
    await page.locator('#content [data-brand="Alpine"]').click();
    const compCount=await page.locator('#content [data-component]').count();
    if(compCount<5)throw new Error('Alpine component navigation did not render');
    await page.locator('#content [data-component="Amplifiers"]').click();
    const products=page.locator('#content article.product');
    const productCount=await products.count();
    if(productCount!==6)throw new Error('Alpine amplifier list should contain 6 source records, got '+productCount);
    const productText=await page.locator('#content').innerText();
    if(/Retail Price|JHB Stock|DBN Stock|CPT Stock|RRP|supplier_stock_snapshot/i.test(productText))throw new Error('Unapproved supplier price/stock leaked into review prototype');
    if(!productText.includes('GW SKU: not assigned')||!productText.includes('Image: not verified'))throw new Error('Pending image/GW SKU controls missing');
    await page.locator('#back').click();
    if(await page.locator('#content [data-component]').count()<5)throw new Error('Back navigation did not return to component list');
    await page.locator('#home').click();
    await page.locator('#hertz').click();
    if(!(await page.locator('#content').innerText()).includes('84 manufacturer records'))throw new Error('Hertz 84-record verification warning missing');
    await page.locator('#content [data-component="Coaxial speakers"]').click();
    if(!(await page.locator('#content').innerText()).includes('staged only'))throw new Error('Hertz component route must remain staged-only');
    await page.locator('#marine').click();
    if(await page.locator('#content article.product').count()!==28)throw new Error('Marine Audio must contain 28 separately routed source records');
    await page.locator('#harness').click();
    if(await page.locator('#content article.product').count()!==47)throw new Error('Harnesses & Trims must contain 47 component-group records');
    await page.locator('#music').click();
    if(!(await page.locator('#content').innerText()).includes('separate from Car Audio') && !(await page.locator('#heading').innerText()).includes('Band Instruments'))throw new Error('Band Instruments are not kept separate');
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+1);
    if(overflow)throw new Error('Horizontal overflow at viewport '+width+'px');
    if(errors.length)throw new Error('Browser errors at '+width+'px: '+errors.join(' | '));
    console.log('PASS viewport '+width+'px: 10 brand choices; brand→component→product navigation; marine/harness separation; Hertz staging guard; no price/stock/image/SKU leaks; no overflow');
    await page.close();
  }
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
