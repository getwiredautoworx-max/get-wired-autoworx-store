const { chromium } = require('playwright');
const fs = require('fs');
fs.mkdirSync('catalogue-review/screenshots',{recursive:true});
(async () => {
  const browser = await chromium.launch({headless:true});
  const widths = [360,390,768,1280];
  for (const width of widths) {
    const page = await browser.newPage({viewport:{width,height:900}});
    const errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
    await page.goto('http://127.0.0.1:4173/catalogue-review/car-audio-navigation-prototype.html',{waitUntil:'domcontentloaded'});
    await page.waitForFunction(()=>document.querySelector('#content [data-brand]')!==null,{timeout:15000});
    if(width===360)await page.screenshot({path:'catalogue-review/screenshots/car-audio-brands-mobile.png',fullPage:true});
    if(width===1280)await page.screenshot({path:'catalogue-review/screenshots/car-audio-brands-desktop.png',fullPage:true});
    const brandCount=await page.locator('#content [data-brand]').count();
    if(brandCount!==10)throw new Error('Expected 9 Planetworld brands plus staged Hertz; got '+brandCount+' at '+width+'px');
    const logoCount=await page.locator('#content [data-brand] img').count();
    if(logoCount!==3)throw new Error('Expected 3 verified official brand logos; got '+logoCount);
    const logosLoaded=await page.locator('#content [data-brand] img').evaluateAll(imgs=>imgs.every(img=>img.complete&&img.naturalWidth>0));
    if(!logosLoaded)throw new Error('One or more official brand logo assets failed to load');
    const labels=await page.locator('#content [data-brand]').allTextContents();
    if(labels.some(x=>/Harnesses & Trims/.test(x)))throw new Error('Harnesses & Trims incorrectly shown as a manufacturer brand');
    if(labels.some(x=>/JBL|Denon DJ/.test(x)))throw new Error('JBL or Denon DJ incorrectly shown as a Car Audio brand');
    await page.locator('#content [data-brand="Alpine"]').click();
    if(width===360)await page.screenshot({path:'catalogue-review/screenshots/car-audio-components-mobile.png',fullPage:true});
    if(width===1280)await page.screenshot({path:'catalogue-review/screenshots/car-audio-components-desktop.png',fullPage:true});
    const compCount=await page.locator('#content [data-component]').count();
    if(compCount<5)throw new Error('Alpine component navigation did not render');
    await page.locator('#content [data-component="Amplifiers"]').click();
    const products=page.locator('#content article.product');
    const productCount=await products.count();
    if(productCount!==6)throw new Error('Alpine amplifier list should contain 6 source records, got '+productCount);
    const productText=await page.locator('#content').innerText();
    if(/Retail Price|JHB Stock|DBN Stock|CPT Stock|RRP|supplier_stock_snapshot/i.test(productText))throw new Error('Unapproved supplier price/stock leaked into review prototype');
    if(!productText.includes('GW SKU: not assigned')||!productText.includes('Image: not verified'))throw new Error('Pending image/GW SKU controls missing');
    await page.locator('#back').click();
    if(await page.locator('#content [data-component]').count()<5)throw new Error('Back navigation did not return to component list');
    await page.locator('#home').click();
    await page.locator('#content [data-brand="Hertz"]').click();
    if(!(await page.locator('#content').innerText()).includes('12 exact official product pages and 12 product-image candidates'))throw new Error('Hertz image verification notice missing');
    await page.locator('#content [data-component="Component speaker kits"]').click();
    if(await page.locator('#content article.hertz-product').count()!==3)throw new Error('Hertz component speaker kits should show 3 exact verified models');
    if(!(await page.locator('#content').innerText()).includes('MPK 165.3')||!(await page.locator('#content').innerText()).includes('CK 130')||!(await page.locator('#content').innerText()).includes('CK 165'))throw new Error('Hertz component model descriptions missing');
    const hertzKitImages=await page.locator('#content img.hertz-product-image').evaluateAll(imgs=>imgs.every(img=>img.complete&&img.naturalWidth>0));
    if(!hertzKitImages)throw new Error('A Hertz component-kit product image failed to load');
    const hertzKitText=await page.locator('#content').innerText();
    if(/Retail Price|JHB Stock|DBN Stock|CPT Stock|RRP/i.test(hertzKitText)||!hertzKitText.includes('GW SKU not assigned'))throw new Error('Hertz review-only price/stock/SKU guard failed');
    await page.locator('#back').click();
    await page.locator('#content [data-component="Coaxial speakers"]').click();
    if(await page.locator('#content article.hertz-product').count()!==4)throw new Error('Hertz coaxial speakers should show 4 exact verified models');
    const hertzCoaxImages=await page.locator('#content img.hertz-product-image').evaluateAll(imgs=>imgs.every(img=>img.complete&&img.naturalWidth>0));
    if(!hertzCoaxImages)throw new Error('A Hertz coaxial product image failed to load');
    await page.locator('#back').click();
    await page.locator('#content [data-component="Standalone subwoofers"]').click();
    const mpsText=await page.locator('#content').innerText();
    if(!mpsText.includes('MPS 250 S2')||!mpsText.includes('MPS 250 S4'))throw new Error('Hertz MPS S2/S4 impedance variants must remain separate');
    await page.locator('#marine').click();
    if(await page.locator('#content article.product').count()!==28)throw new Error('Marine Audio must contain 28 separately routed source records');
    await page.locator('#harness').click();
    if(await page.locator('#content article.product').count()!==47)throw new Error('Harnesses & Trims must contain 47 component-group records');
    await page.locator('#music').click();
    if(!(await page.locator('#content').innerText()).includes('separate from Car Audio') && !(await page.locator('#heading').innerText()).includes('Band Instruments'))throw new Error('Band Instruments are not kept separate');
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+1);
    if(overflow)throw new Error('Horizontal overflow at viewport '+width+'px');
    await page.goto('http://127.0.0.1:4173/catalogue-review/band-instruments-navigation-prototype.html',{waitUntil:'domcontentloaded'});
    await page.waitForFunction(()=>document.querySelector('#content [data-section]')!==null,{timeout:15000});
    if(width===360)await page.screenshot({path:'catalogue-review/screenshots/music-sections-mobile.png',fullPage:true});
    if(width===1280)await page.screenshot({path:'catalogue-review/screenshots/music-sections-desktop.png',fullPage:true});
    if(await page.locator('#content [data-section]').count()!==4)throw new Error('Expected 4 separate music sections at '+width+'px');
    await page.locator('#content [data-section="Band Instruments"]').click();
    if(await page.locator('#content [data-brand]').count()!==7)throw new Error('Band Instruments should have 7 source brands');
    if(width===360)await page.screenshot({path:'catalogue-review/screenshots/band-instruments-brands-mobile.png',fullPage:true});
    if(width===1280)await page.screenshot({path:'catalogue-review/screenshots/band-instruments-brands-desktop.png',fullPage:true});
    const bandLabels=await page.locator('#content [data-brand]').allTextContents();
    if(bandLabels.some(x=>/JBL|Denon DJ|M-Audio/.test(x)))throw new Error('Studio/DJ brands leaked into Band Instruments');
    await page.locator('#content [data-brand="Ibanez"]').click();
    if(await page.locator('#content [data-component]').count()<5)throw new Error('Ibanez component navigation did not render');
    await page.locator('#content [data-component="Guitars & Basses"]').click();
    if(await page.locator('#content article.product').count()!==393)throw new Error('Ibanez Guitars & Basses should contain 393 source rows');
    const musicText=await page.locator('#content').innerText();
    if(/Retail Price|JHB Stock|DBN Stock|CPT Stock|RRP|supplier_stock_snapshot/i.test(musicText))throw new Error('Music supplier price/stock leaked into review prototype');
    if(!musicText.includes('GW SKU: not assigned')||!musicText.includes('Image: not verified'))throw new Error('Music image/GW SKU review guards missing');
    await page.locator('#back').click();
    await page.locator('#back').click();
    await page.locator('#back').click();
    await page.locator('#content [data-section="Studio & Pro Audio"]').click();
    if(!(await page.locator('#content').innerText()).includes('JBL'))throw new Error('JBL should remain in Studio & Pro Audio, not Band Instruments');
    await page.locator('#home').click();
    await page.locator('#content [data-section="DJ Equipment"]').click();
    if(await page.locator('#content [data-brand]').count()!==4)throw new Error('DJ Equipment should have 4 source brands');
    const musicOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+1);
    if(musicOverflow)throw new Error('Music prototype horizontal overflow at '+width+'px');
    if(errors.length)throw new Error('Browser errors at '+width+'px: '+errors.join(' | '));
    console.log('PASS viewport '+width+'px: Car Audio + Band Instruments/Studio/DJ navigation, source guards, no overflow');
    await page.close();
  }
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
