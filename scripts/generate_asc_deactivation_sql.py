#!/usr/bin/env python3
"""Generate a human-review SQL patch for explicit ASC discontinued matches.

This generator writes SQL to a file only. It does not connect to Supabase or
execute SQL. Temporary stockouts and duplicate-SKU rows are excluded.
"""
import argparse
import csv
import sys
from pathlib import Path


def sql_literal(value):
    return "'" + str(value or "").replace("'", "''") + "'"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--review-csv", required=True, help="asc_store_review_patch.csv")
    ap.add_argument("--output", default="asc-deactivation-review.sql")
    args = ap.parse_args()
    try:
        with open(args.review_csv, newline="", encoding="utf-8-sig") as handle:
            reader = csv.DictReader(handle)
            if not reader.fieldnames:
                raise ValueError("Review CSV is missing its header.")
            rows = list(reader)
    except (OSError, csv.Error, ValueError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2

    eligible = []
    for row in rows:
        if (row.get("recommended_action") or "").strip() != "DEACTIVATE_AFTER_REVIEW":
            continue
        if (row.get("store_active") or "").strip().lower() not in {"true", "t", "1"}:
            continue
        sku = (row.get("supplier_sku") or "").strip()
        if not sku:
            continue
        eligible.append(row)

    lines = [
        "-- REVIEW ONLY: generated by scripts/generate_asc_deactivation_sql.py",
        "-- DO NOT RUN until each ASC listing is confirmed orderable/discontinued with the supplier.",
        "-- This file is not executed by any workflow. It only proposes active=false; it does not delete rows.",
        "BEGIN;",
        "",
    ]
    for row in eligible:
        sku = (row.get("supplier_sku") or "").strip()
        public_sku = (row.get("public_sku") or "").replace("\n", " ").replace("\r", " ")
        name = (row.get("store_name") or "").replace("\n", " ").replace("\r", " ")
        title = (row.get("asc_listing_title") or "").replace("\n", " ").replace("\r", " ")
        url = (row.get("asc_listing_url") or "").replace("\n", " ").replace("\r", " ")
        lines.extend([
            f"-- Supplier SKU: {sku}; public SKU: {public_sku}; store item: {name}",
            f"-- ASC evidence: {title} | {url}",
            f"UPDATE public.products SET active = false, updated_at = now() WHERE sku = {sql_literal(sku)} AND active = true;",
            "",
        ])
    lines.extend([
        f"-- Proposed deactivations: {len(eligible)}",
        "-- Default is ROLLBACK. Review every affected row count; replace ROLLBACK with COMMIT only after owner approval.",
        "-- COMMIT; -- Uncomment only after supplier verification and owner approval.",
        "ROLLBACK;",
        "",
    ])
    Path(args.output).write_text("\n".join(lines), encoding="utf-8")
    print(f"Proposed deactivations: {len(eligible)}")
    print(f"SQL patch written to: {Path(args.output)}")
    print("Safety: no database connection or writes were performed.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
