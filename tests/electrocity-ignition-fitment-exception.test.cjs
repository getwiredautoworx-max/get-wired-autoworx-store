'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = path.join(__dirname, '..', 'suppliers', 'Electrocity', 'catalogue-work', 'ignition-looms-modules');
const csv = fs.readFileSync(path.join(base, 'normalised-review.csv'), 'utf8').trim().split(/\r?\n/);
const headers = csv[0].split(',');
function parseLine(line) { const out=[]; let v='',q=false; for(let i=0;i<line.length;i++){const c=line[i];if(q){if(c==='"'&&line[i+1]==='"'){v+='"';i++;}else if(c==='"')q=false;else v+=c;}else if(c==='"')q=true;else if(c===','){out.push(v);v='';}else v+=c;}out.push(v);return Object.fromEntries(headers.map((h,i)=>[h,out[i]??''])); }
const rows=csv.slice(1).map(parseLine);
assert.equal(rows.length,29);
const row=rows.find(r=>r.manufacturer_model==="IG-T003");
assert.ok(row);
assert.equal(row.supplier_sku,"220547");
assert.equal(row.proposed_gw_sku,"GWA-EC-000012");
assert.equal(row.confidence,"corroborated");
assert.equal(row.qa_status,"REVIEW_PASSED_SOURCE_DISCREPANCY_EXCLUDED");
const apps=JSON.parse(row.vehicle_applications_corroborated_json);
assert.ok(apps.some(x=>x.make==="Toyota"&&x.model.includes("Corolla (E8)")));
assert.ok(apps.some(x=>x.make==="Toyota"&&x.model.includes("Starlet (EP91)")));
assert.equal(JSON.parse(row.vehicle_applications_possible_json).length,0);
assert.doesNotMatch(row.vehicle_applications_corroborated_json,/Fiat|Peugeot|Renault/i);
assert.match(row.fitment_research_sources_json,/mobiletron\.com\/Product\/detail\/2801\/IG-T003/);
assert.match(row.fitment_research_sources_json,/niparts\.com\/Fac\/ADFED5\/WAIglobal\/ICM597/);
assert.equal(row.import_status,"REVIEW_ONLY_NOT_IMPORTED");
const exception=fs.readFileSync(path.join(base,'exceptions.csv'),'utf8');
assert.match(exception,/SOURCE_DESCRIPTION_DISCREPANCY_EXCLUDED/);
assert.match(exception,/FIAT\/PEUGEOT\/RENAUL/);
console.log("PASS: 29 Electrocity ignition pilot rows; IG-T003 source-caption conflict resolved for customer-facing scope with corroborated Toyota OE applications; unsupported Fiat/Peugeot/Renault excluded; no import or commercial values.");
